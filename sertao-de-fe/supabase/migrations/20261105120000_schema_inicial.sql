-- Esquema inicial do Sertão de Fé.
-- As colunas usam os mesmos nomes dos campos do front-end (public/index.html).

-- Equipe: só quem está nesta tabela edita conteúdo. Uma conta no Auth, sozinha, não dá acesso.
create table public.equipe (
  user_id uuid primary key references auth.users (id) on delete cascade,
  nome text not null
);

create function public.is_equipe()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (select 1 from public.equipe where user_id = auth.uid());
$$;

create table public.capelas (
  id bigint generated by default as identity primary key,
  num integer not null,
  slug text not null unique,
  name text not null,
  padroeiro text not null default '',
  zona text not null check (zona in ('urbana', 'rural', 'distrital')),
  localidade text not null default '',
  ano text not null default '',
  festa text not null default '',
  estilo text not null default '',
  conservacao text not null default '',
  guardiao text not null default '',
  lat double precision not null,
  lng double precision not null,
  historia text not null default '',
  citacao text not null default '',
  transcricao text not null default '',
  destaque boolean not null default false,
  status text not null default 'Rascunho' check (status in ('Rascunho', 'Em revisão', 'Publicado')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- removed_at funciona como lixeira: o registro e o arquivo são mantidos e podem ser restaurados.
create table public.midias (
  id uuid primary key default gen_random_uuid(),
  capela_id bigint not null references public.capelas (id) on delete cascade,
  type text not null check (type in ('foto', 'audio', 'video')),
  url text not null,
  storage_path text,
  caption text not null default '',
  alt text not null default '',
  credit text not null default '',
  cover boolean not null default false,
  embed boolean not null default false,
  position integer not null default 0,
  removed_at timestamptz,
  created_at timestamptz not null default now()
);
create index midias_capela_id_idx on public.midias (capela_id, position);

create table public.atividades (
  id bigint generated by default as identity primary key,
  capela_id bigint references public.capelas (id) on delete set null,
  user_id uuid default auth.uid() references auth.users (id) on delete set null,
  who text not null,
  what text not null,
  created_at timestamptz not null default now()
);
create index atividades_created_at_idx on public.atividades (created_at desc);

create function public.touch_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

create trigger capelas_touch_updated_at
  before update on public.capelas
  for each row execute function public.touch_updated_at();

-- Permissões. Não há DELETE: capelas saem do ar por status e mídias vão para a lixeira.
grant select on public.capelas, public.midias to anon, authenticated;
grant insert, update on public.capelas, public.midias to authenticated;
grant select on public.equipe to authenticated;
grant select, insert on public.atividades to authenticated;
grant usage on all sequences in schema public to authenticated;
grant execute on function public.is_equipe() to anon, authenticated;

alter table public.equipe enable row level security;
alter table public.capelas enable row level security;
alter table public.midias enable row level security;
alter table public.atividades enable row level security;

create policy "membro lê o próprio registro" on public.equipe
  for select to authenticated
  using (user_id = auth.uid());

create policy "público lê capelas publicadas" on public.capelas
  for select to anon, authenticated
  using (status = 'Publicado');

create policy "equipe lê todas as capelas" on public.capelas
  for select to authenticated
  using (public.is_equipe());

create policy "equipe cria capelas" on public.capelas
  for insert to authenticated
  with check (public.is_equipe());

create policy "equipe edita capelas" on public.capelas
  for update to authenticated
  using (public.is_equipe())
  with check (public.is_equipe());

create policy "público lê mídias de capelas publicadas" on public.midias
  for select to anon, authenticated
  using (
    removed_at is null
    and exists (
      select 1 from public.capelas c
      where c.id = capela_id and c.status = 'Publicado'
    )
  );

create policy "equipe lê todas as mídias" on public.midias
  for select to authenticated
  using (public.is_equipe());

create policy "equipe cria mídias" on public.midias
  for insert to authenticated
  with check (public.is_equipe());

create policy "equipe edita mídias" on public.midias
  for update to authenticated
  using (public.is_equipe())
  with check (public.is_equipe());

create policy "equipe lê atividades" on public.atividades
  for select to authenticated
  using (public.is_equipe());

create policy "equipe registra atividades" on public.atividades
  for insert to authenticated
  with check (public.is_equipe() and user_id = auth.uid());

-- Storage: bucket público para leitura; só a equipe envia. Sem política de DELETE.
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('midias', 'midias', true, 52428800, array['image/*', 'video/*', 'audio/*'])
on conflict (id) do nothing;

create policy "equipe envia arquivos" on storage.objects
  for insert to authenticated
  with check (bucket_id = 'midias' and public.is_equipe());
